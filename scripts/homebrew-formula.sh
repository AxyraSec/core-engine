#!/usr/bin/env bash
# Prints the Homebrew formula for a release, from its checksums.txt.
# The release workflow attaches the result as core-engine.rb; copy it to
# Formula/core-engine.rb in the AxyraSec/homebrew-tap repository.
#
#   scripts/homebrew-formula.sh <version> <checksums.txt>
set -euo pipefail

version=${1:?usage: scripts/homebrew-formula.sh <version> <checksums.txt>}
checksums=${2:?usage: scripts/homebrew-formula.sh <version> <checksums.txt>}
base="https://github.com/AxyraSec/core-engine/releases/download/${version}"

sum() {
  local s
  s=$(awk -v f="$1" '$2 == f { print $1 }' "$checksums")
  [ -n "$s" ] || { echo "missing $1 in $checksums" >&2; exit 1; }
  echo "$s"
}

# Computed first so that a missing platform stops the script.
darwin_arm64=$(sum engine_darwin_arm64)
darwin_amd64=$(sum engine_darwin_amd64)
linux_arm64=$(sum engine_linux_arm64)
linux_amd64=$(sum engine_linux_amd64)

cat <<RUBY
# Generated by scripts/homebrew-formula.sh for ${version}.
class CoreEngine < Formula
  desc "Runtime authorization for AI agents using MCP tools"
  homepage "https://axyra.fr"
  version "${version#v}"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "${base}/engine_darwin_arm64"
      sha256 "${darwin_arm64}"
    end
    on_intel do
      url "${base}/engine_darwin_amd64"
      sha256 "${darwin_amd64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/engine_linux_arm64"
      sha256 "${linux_arm64}"
    end
    on_intel do
      url "${base}/engine_linux_amd64"
      sha256 "${linux_amd64}"
    end
  end

  def install
    bin.install Dir["engine_*"].first => "engine"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/engine")
  end
end
RUBY
